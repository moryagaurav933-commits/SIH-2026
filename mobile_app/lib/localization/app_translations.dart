  /// Retrieve localized string for a given key and language.
  static String get(String key, AppLanguage language) {
    final entry = _localizedValues[key];
    if (entry == null) return key;
    return entry[language] ?? entry[AppLanguage.hinglish] ?? key;
  }

  /// Helper to get string from current BuildContext
  static String of(BuildContext context, String key) {
    final provider = Provider.of<LanguageProvider>(context, listen: false);
    return get(key, provider.currentLanguage);
  }
}

/// Extension on BuildContext for quick access: `context.tr('key')`
extension LocalizationExt on BuildContext {
  String tr(String key) {
    try {
      final provider = Provider.of<LanguageProvider>(this, listen: true);
      return AppTranslations.get(key, provider.currentLanguage);
    } catch (_) {
      return AppTranslations.get(key, AppLanguage.hinglish);
    }
  }

  AppLanguage get currentLanguage {
    try {
      return Provider.of<LanguageProvider>(this, listen: true).currentLanguage;
    } catch (_) {
      return AppLanguage.hinglish;
    }
  }
